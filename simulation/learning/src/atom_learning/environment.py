"""Gymnasium MDP for bounded joint commands on a URDF kinematic prototype."""

from dataclasses import dataclass
import json
from pathlib import Path

import gymnasium as gym
from gymnasium import spaces
import numpy as np

from .model import UrdfModel, vector


def load_config(path):
    path = Path(path).resolve()
    config = json.loads(path.read_text(encoding='utf-8'))
    config['model'] = str((path.parent / config['model']).resolve())
    validate_config(config)
    return config


def validate_config(config):
    if config.get('profile') != 'uncalibrated-urdf-prototype-v1':
        raise ValueError('Only the explicitly uncalibrated simulation profile is supported')
    positive = ('dt', 'velocity_fraction', 'action_slew_per_step', 'sampling_fraction',
                'position_tolerance_m', 'orientation_tolerance_rad', 'joint_tolerance_fraction')
    for key in positive:
        value = config[key]
        if not np.isfinite(value) or value <= 0:
            raise ValueError(f'Invalid {key}')
    if config['velocity_fraction'] > 1 or config['sampling_fraction'] >= 1:
        raise ValueError('Fractions exceed allowed range')
    if config['action_slew_per_step'] > 2:
        raise ValueError('Invalid action slew')
    if not isinstance(config['horizon'], int) or config['horizon'] <= 0:
        raise ValueError('Invalid horizon')
    for key in ('progress', 'distance', 'time', 'smoothness', 'success', 'failure'):
        if not np.isfinite(config['reward'][key]) or config['reward'][key] < 0:
            raise ValueError('Invalid reward coefficient')


@dataclass(frozen=True)
class ControlResult:
    position: np.ndarray
    velocity: np.ndarray
    applied_action: np.ndarray
    limit_violation: bool


class KinematicController:
    """Independent limit/velocity/action-slew layer, with an explicit stop state.

    No inertial integration or torque model. Slew is an experimental command
    filter, not a measured actuator acceleration. No hardware transport exists.
    """

    def __init__(self, model, config):
        self.model = model
        self.dt = config['dt']
        self.max_velocity = model.velocity * config['velocity_fraction']
        self.slew = config['action_slew_per_step']
        self.reset(model.center)

    def reset(self, q):
        self.q = self.model.validate(q).copy()
        self.action = np.zeros(self.model.dof)
        self.stopped = False

    def stop(self):
        self.stopped = True
        self.action[:] = 0

    def command(self, action):
        if self.stopped:
            raise RuntimeError('Controller stopped; reset required')
        requested = vector(action, self.model.dof)
        if np.any(np.abs(requested) > 1.0 + 1e-6):
            raise ValueError('Normalized action outside [-1, 1]')
        applied = np.clip(requested, self.action - self.slew, self.action + self.slew)
        proposed = self.q + applied * self.max_velocity * self.dt
        limited = np.clip(proposed, self.model.lower, self.model.upper)
        violation = not np.allclose(proposed, limited, atol=1e-12, rtol=0)
        velocity = (limited - self.q) / self.dt
        self.q = limited
        self.action = applied
        if violation:
            self.stop()
        return ControlResult(limited.copy(), velocity, applied.copy(), violation)


def reward_value(before, after, smoothness, success, failure, weights):
    if failure:
        return -float(weights['failure'])
    return float(weights['progress'] * (before - after) - weights['distance'] * after
                 - weights['time'] - weights['smoothness'] * smoothness
                 + weights['success'] * success)


class ReachEnv(gym.Env):
    """Learn a servo for joint targets supplied by a Cartesian task planner.

    State: normalized joints, normalized target-joint error, previous applied
    command, and remaining horizon. These determine the complete next state.
    Targets are sampled by joint configuration inside a configured region;
    their observable link poses are generated by FK. Cartesian requests enter
    through reset(options={'target_pose': ...}) and bounded IK.
    """

    metadata = {'render_modes': []}

    def __init__(self, config):
        super().__init__()
        validate_config(config)
        self.config = config
        self.model = UrdfModel(config['model'], config['tip'])
        self.controller = KinematicController(self.model, config)
        n = self.model.dof
        self.action_space = spaces.Box(-1, 1, (n,), dtype=np.float32)
        self.observation_space = spaces.Box(-1, 1, (3 * n + 1,), dtype=np.float32)
        self.done = True

    def _observation(self):
        model = self.model
        return np.r_[2 * (self.controller.q - model.center) / model.span,
                     (self.goal - self.controller.q) / model.span,
                     self.controller.action,
                     max(0, 1 - self.steps / self.config['horizon'])].astype(np.float32)

    def _distance(self):
        return float(np.linalg.norm((self.goal - self.controller.q) / self.model.span))

    def _info(self, reason='running'):
        error = self.model.pose_error(self.target_pose, self.controller.q)
        return {
            'status': reason, 'is_success': reason == 'success',
            'position_error_m': float(np.linalg.norm(error[:3])),
            'orientation_error_rad': float(np.linalg.norm(error[3:])),
            'joint_error_fraction': self._distance(), 'steps': self.steps,
            'simulated_time_s': self.steps * self.config['dt'],
            'limit_violations': self.limit_violations,
            'collisions': None, 'collision_detection': 'not_modeled',
            'control_effort': None, 'grasp_success': None,
            'model_fidelity': self.config['profile'],
        }

    def reset(self, *, seed=None, options=None):
        super().reset(seed=seed)
        options = options or {}
        if set(options) - {'initial_q', 'goal_q', 'target_pose'}:
            raise ValueError('Unknown reset option')
        if 'goal_q' in options and 'target_pose' in options:
            raise ValueError('Choose joint target or Cartesian pose, not both')
        half = self.model.span * self.config['sampling_fraction'] / 2
        initial = options.get('initial_q', self.np_random.uniform(self.model.center - half,
                                                               self.model.center + half))
        initial = self.model.validate(initial)
        if 'target_pose' in options:
            goal = self.model.ik(options['target_pose'], initial)
            if goal is None:
                raise ValueError('Target pose not solved inside joint limits')
        else:
            goal = options.get('goal_q', self.np_random.uniform(self.model.center - half,
                                                              self.model.center + half))
        self.goal = self.model.validate(goal).copy()
        self.target_pose = self.model.fk(self.goal)
        self.controller.reset(initial)
        self.steps = self.limit_violations = 0
        self.done = False
        return self._observation(), self._info()

    def stop(self):
        self.controller.stop()

    def step(self, action):
        if self.done:
            raise RuntimeError('Episode ended; reset before step')
        before = self._distance()
        previous = self.controller.action.copy()
        reason = 'running'
        if self.controller.stopped:
            reason = 'interrupted'
        else:
            try:
                result = self.controller.command(action)
                if result.limit_violation:
                    self.limit_violations += 1
                    reason = 'joint_limit'
            except ValueError:
                self.controller.stop()
                reason = 'invalid_action'
        self.steps += 1
        info = self._info(reason)
        failure = reason in ('interrupted', 'joint_limit', 'invalid_action')
        success = (not failure
                   and info['position_error_m'] <= self.config['position_tolerance_m']
                   and info['orientation_error_rad'] <= self.config['orientation_tolerance_rad']
                   and info['joint_error_fraction'] <= self.config['joint_tolerance_fraction'])
        terminated = bool(success or failure)
        truncated = bool(not terminated and self.steps >= self.config['horizon'])
        if success:
            reason = 'success'
        elif truncated:
            reason = 'timeout'
        self.done = terminated or truncated
        smoothness = float(np.mean((self.controller.action - previous) ** 2))
        reward = reward_value(before, self._distance(), smoothness, success, failure,
                              self.config['reward'])
        info.update(self._info(reason))
        info['command_change_squared'] = smoothness
        return self._observation(), reward, terminated, truncated, info


def conventional_action(env):
    """Proportional reference through the same bounded controller as SAC."""
    delta = env.controller.max_velocity * env.config['dt']
    return np.clip(0.35 * (env.goal - env.controller.q) / delta, -1, 1).astype(np.float32)
